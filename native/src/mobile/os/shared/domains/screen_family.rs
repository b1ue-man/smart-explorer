//! Family methods use the same pure gate as the desktop viewer. JSON keys
//! remain native snake_case inside the family DTO; no lossy recursive rewrite.
use super::*;
use crate::screen::core::family_protocol::FamilyOperation;
use crate::screen::core::wire_control::HostFrame;

pub(super) fn handle(method:&str,args:&Value)->Option<Result<Value,ApiError>> {
    Some(match method {
        "screen.families"=>listing(args),
        "screen.viewFamilyState"=>state(args),
        "screen.viewFamilySnapshot"=>session_arg(args).and_then(|s|s.send(&ViewerFrame::FamilySnapshot)).map(|()|json!({})),
        "screen.viewFamilyOperation"=>operation(args),
        "screen.viewFamilyInput"=>input(args),
        _=>return None,
    })
}
fn listing(args:&Value)->Result<Value,ApiError> {
    let target=Target::parse(args)?;target.check(&profiles())?;
    let list=match opt_str(args,"expectedNodeId") {
        Some(node)=>crate::daemon::screen_families_for_node(target.peer(),node,None,|_|{}),
        None=>crate::daemon::screen_families(target.peer(),None,|_|{}),
    }
        .map_err(|error|ApiError::new("network",error))?;
    serde_json::to_value(list).map_err(|error|ApiError::internal(error.to_string()))
}
fn state(args:&Value)->Result<Value,ApiError> {
    let session=session_arg(args)?;let guard=lock(&session.family);
    let family=guard.as_ref().ok_or_else(||invalid("Keine Familienansicht."))?;
    Ok(json!({"snapshot":family.snapshot,"notice":family.notice,"last_operation":family.last_operation}))
}
fn operation(args:&Value)->Result<Value,ApiError> {
    let session=session_arg(args)?;
    if !session.control_allowed.load(Ordering::SeqCst){return Err(no_control());}
    let request:FamilyOperation=serde_json::from_value(args.get("request").cloned().ok_or_else(||invalid("Fensteranfrage fehlt."))?)
        .map_err(|error|invalid(error.to_string()))?;
    request.validate().map_err(|error|invalid(error.to_string()))?;
    let generated=lock(&session.family).as_mut().ok_or_else(||invalid("Keine Familienansicht."))?
        .operation(request.identity,request.operation).map_err(|error|invalid(error.to_string()))?;
    // Return the actual correlation key generated by the viewer, not the UI key.
    session.send(&ViewerFrame::FamilyOperation(generated.clone()))?;
    Ok(json!({"request_id":generated.request_id}))
}
fn input(args:&Value)->Result<Value,ApiError> {
    let session=session_arg(args)?;
    route_input(&session,parse_events(args)?)?;Ok(json!({}))
}
pub(super) fn route_input(session:&ViewSession,events:Vec<InputEvent>)->Result<(),ApiError> {
    if !session.control_allowed.load(Ordering::SeqCst){return Err(no_control());}
    if !session.family_presented.load(Ordering::SeqCst) {
        return Err(ApiError::new("busy","Das aktuelle Familienbild wurde noch nicht dargestellt."));
    }
    let frames=lock(&session.family).as_mut().ok_or_else(||invalid("Keine Familienansicht."))?
        .input(events).map_err(|error|invalid(error.to_string()))?;
    if !session.family_presented.load(Ordering::SeqCst) {return Ok(());}
    for frame in frames {session.send(&frame)?;}
    Ok(())
}
pub(super) fn event(session:&ViewSession,frame:&HostFrame)->Option<Result<bool,ApiError>> {
    let mut state=lock(&session.family);let family=state.as_mut()?;
    let result=match frame {
        HostFrame::FamilySnapshot(snapshot)=>family.receive(snapshot.clone()).map(|changed|(changed,Vec::new())),
        HostFrame::FamilyOperation(result)=>family.result(result.clone()),
        HostFrame::FamilyInput(result)=>{
            if result.blocked.is_some()||result.reason.is_some() {family.disarm();family.notice=Some(result.reason.clone()
                .unwrap_or_else(||format!("Eingabe gesperrt: {:?}",result.blocked)));}
            Ok((false,Vec::new()))
        }
        HostFrame::ControlState(state) if state.blocked.is_some()||state.holder.is_none()=>{family.disarm();return None;}
        HostFrame::State(report) if report.state!=crate::screen::core::session_state::SessionState::Streaming=>{
            family.disarm();session.family_presented.store(false,Ordering::SeqCst);return None;
        }
        _=>return None,
    };
    let payload=json!({"snapshot":family.snapshot,"notice":family.notice,"last_operation":family.last_operation});
    if result.as_ref().is_ok_and(|(changed,_)|*changed) {session.family_presented.store(false,Ordering::SeqCst);}
    drop(state);
    Some(result.map_err(|error|invalid(error.to_string())).and_then(|(changed,frames)| {
        if changed {session.family_presented.store(false,Ordering::SeqCst);}
        if session.family_presented.load(Ordering::SeqCst) {for frame in frames {session.send(&frame)?;}}
        if let Some(rt)=Runtime::installed(){rt.emit(json_shapes::event_value(session.id,"family",payload));}
        Ok(changed)
    }))
}
