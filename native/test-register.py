#!/usr/bin/env python3
"""The test register (docs/tests/register.tsv) names every test of the repository.

Each row names the requirement the test protects, its verdict and the suite that runs it. With the
register, a failing test can be told apart: either it is outdated, or it shows a real problem
(TESTS-BEWERTUNG, docs/tests/README.md).

Tests are `#[test]` and `#[tokio::test]` functions, the tests a `macro_rules!` macro generates (one
per `<name> =>` of its invocations) and Kotlin `@Test` methods.

This check fails when:
- a test exists in the code without a row;
- a row names a test that no longer exists;
- a row is malformed;
- a row names a suite that has no workflow;
- a macro defines tests whose names the check cannot read.

It reads source text only: it compiles nothing and starts nothing. crates-task runs it on Linux;
`python3 native/test-register.py` runs it anywhere.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REGISTER = REPO / "docs" / "tests" / "register.tsv"
HEADER = ["Datei", "Test", "Urteil", "Kategorie", "Schützt", "Suite"]
VERDICTS = {"behalten", "unklar"}
CATEGORY = re.compile(r"^(K[1-5](/K[1-5])*|U)$")
RUST_ROOTS = ("native/crates", "native/src", "native/tests", "share-server", "se-agent")
KOTLIN_ROOTS = ("android/app/src/test", "android/app/src/androidTest")
# A Rust test: #[test] or #[tokio::test(...)], further attributes, then the function.
RUST_TEST = re.compile(r"#\[(?:tokio::)?test\b[^\]]*\]((?:\s*#\[[^\]]*\])*)\s*"
                       r"(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)")
KOTLIN_TEST = re.compile(r"@Test\b(?:\([^)]*\))?((?:\s*@\w+(?:\([^)]*\))?)*)\s*"
                         r"(?:(?:public|internal|private)\s+)?fun\s+`?([^`(]+)`?\s*\(")
# A test a `macro_rules!` macro generates: `#[test]`, further attributes, then `fn $<parameter>`. Each
# invocation names its tests as `<name> => ...` (the matcher `$<parameter>:ident =>`); the name is the
# test's name, the macro's attributes are its attributes.
MACRO_RULES = re.compile(r"macro_rules!\s*(\w+)\s*\{")
MACRO_TEST = re.compile(r"#\[(?:tokio::)?test\b[^\]]*\]((?:\s*#\[[^\]]*\])*)\s*(?:pub(?:\([^)]*\))?\s+)?"
                        r"(?:async\s+)?fn\s+\$(\w+)")
# "keine (<reason>)" marks a test no suite runs, with the reason; every other value is a workflow name.
NO_SUITE = re.compile(r"^keine \(.+\)$")


def _braced(text: str, start: int, opening: str, closing: str) -> int:
    """Index after the delimiter that closes the one opened just before `start`."""
    depth = 1
    index = start
    while index < len(text) and depth:
        if text[index] == opening:
            depth += 1
        elif text[index] == closing:
            depth -= 1
        index += 1
    return index


def macro_tests(text: str) -> tuple[list[tuple[str, str]], list[str]]:
    """The tests the `macro_rules!` macros of one file generate, as (name, attributes), and the macros
    whose test names this check cannot read (a matcher other than `$<parameter>:ident =>`)."""
    tests: list[tuple[str, str]] = []
    unreadable: list[str] = []
    for definition in MACRO_RULES.finditer(text):
        body = text[definition.end():_braced(text, definition.end(), "{", "}") - 1]
        generated = MACRO_TEST.search(body)
        if not generated:
            continue
        name, parameter = definition.group(1), generated.group(2)
        if not re.search(r"\$" + parameter + r":ident\s*=>", body):
            unreadable.append(name)
            continue
        for call in re.finditer(r"(?<![\w!])" + name + r"!\s*([\{\(\[])", text):
            opening = call.group(1)
            closing = {"{": "}", "(": ")", "[": "]"}[opening]
            arguments = text[call.end():_braced(text, call.end(), opening, closing) - 1]
            # Only the top level of the invocation: `=>` inside a nested expression names no test.
            depth, top = 0, []
            for character in arguments:
                depth += character in "([{"
                depth -= character in ")]}"
                top.append(character if depth == 0 else " ")
            for found in re.finditer(r"\b([A-Za-z_]\w*)\s*=>", "".join(top)):
                tests.append((found.group(1), generated.group(1)))
    return tests, unreadable


def rust_tests(text: str) -> list[tuple[str, str]]:
    """The Rust tests of one file, written out or generated by a macro, as (name, attributes)."""
    written = [(match.group(2).strip(), match.group(1)) for match in RUST_TEST.finditer(text)]
    return written + macro_tests(text)[0]


def tests_in_code(problems: list[str] | None = None) -> set[tuple[str, str]]:
    found: set[tuple[str, str]] = set()
    for roots, suffix in ((RUST_ROOTS, "*.rs"), (KOTLIN_ROOTS, "*.kt")):
        for root in roots:
            base = REPO / root
            if not base.is_dir():
                continue
            for path in sorted(base.rglob(suffix)):
                if "/target/" in path.as_posix():
                    continue
                text = path.read_text(encoding="utf-8", errors="replace")
                relative = path.relative_to(REPO).as_posix()
                if suffix == "*.rs":
                    for name, _ in rust_tests(text):
                        found.add((relative, name))
                    if problems is not None:
                        problems.extend(f"{relative}: macro_rules! {name} defines tests whose names this check "
                                        "cannot read (expected the matcher `$<name>:ident =>`)"
                                        for name in macro_tests(text)[1])
                else:
                    for match in KOTLIN_TEST.finditer(text):
                        found.add((relative, match.group(2).strip()))
    return found


def workflows() -> set[str]:
    return {path.stem for path in (REPO / ".github" / "workflows").glob("*.yml")}


def main() -> int:
    if not REGISTER.is_file():
        print(f"register missing: {REGISTER.relative_to(REPO)}")
        return 1
    lines = REGISTER.read_text(encoding="utf-8").splitlines()
    problems: list[str] = []
    if not lines or lines[0].split("\t") != HEADER:
        problems.append(f"line 1: header must be {chr(9).join(HEADER)!r}")
    known = workflows()
    rows: dict[tuple[str, str], int] = {}
    for number, line in enumerate(lines[1:], 2):
        cells = line.split("\t")
        if len(cells) != len(HEADER):
            problems.append(f"line {number}: {len(cells)} columns instead of {len(HEADER)}")
            continue
        path, name, verdict, category, protects, suite = cells
        key = (path, name)
        if key in rows:
            problems.append(f"line {number}: {path} {name} also in line {rows[key]}")
        rows[key] = number
        if verdict not in VERDICTS:
            problems.append(f"line {number}: verdict {verdict!r} (allowed: {', '.join(sorted(VERDICTS))})")
        if not CATEGORY.match(category):
            problems.append(f"line {number}: category {category!r} (K1 to K5, joined with '/', or U)")
        if (verdict == "unklar") != (category == "U"):
            problems.append(f"line {number}: verdict {verdict} with category {category}")
        if not protects.strip():
            problems.append(f"line {number}: no requirement in column Schützt")
        for value in (part.strip() for part in suite.split(",")):
            if not (value in known or NO_SUITE.match(value)):
                problems.append(f"line {number}: suite {value!r} is no workflow under .github/workflows "
                                "and not 'keine (<reason>)'")
    code = tests_in_code(problems)
    for path, name in sorted(code - rows.keys()):
        problems.append(f"{path}: test {name} has no row in docs/tests/register.tsv")
    for path, name in sorted(rows.keys() - code):
        problems.append(f"line {rows[(path, name)]}: test {name} no longer exists in {path}")
    if problems:
        print(f"test register: {len(problems)} problems")
        for problem in problems[:200]:
            print(f"- {problem}")
        if len(problems) > 200:
            print(f"- ... {len(problems) - 200} more")
        return 1
    print(f"test register: {len(rows)} tests, every one in the code and every one registered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
